def _get_secret(key, default=""):
    """يقرأ القيمة من st.secrets أولاً ثم من متغيرات البيئة، مع تنظيف آمن."""
    try:
        val = st.secrets.get(key, None)
        if val is not None:
            return str(val).strip()
    except Exception:
        pass
    return str(os.environ.get(key, default)).strip()


